func TestCmdCipherKeySwitch(t *testing.T) {
	c := newCmdCipher()
	initCmd := []byte{
		0x0f, 0xf0, 0xe0, 0x20, 0x00, 0x00, 0x00, 0x00, 0x23, 0x8d, 0xc0, 0xd0, 0x0e, 0xd0, 0x38, 0x75,
		0xe8, 0x38, 0xdf, 0xeb, 0x33, 0x7d, 0x39, 0x52, 0xe3, 0x78, 0xeb, 0xd1, 0xb7, 0x84, 0xef, 0x65,
		0x00, 0x9a,
	}
	encInit, err := c.EncryptCommand(initCmd)
	if err != nil {
		t.Fatalf("EncryptCommand(init): %v", err)
	}
	if encInit[0] != 0x0f || encInit[1] != 0xf0 {
		t.Fatalf("header bytes altered: %x %x", encInit[0], encInit[1])
	}

	// 次の通常コマンドは initCmd[16:32] の AES-128 鍵で暗号化されるはず
	fwCmd := []byte{0x1f, 0xf0, 0x9f, 0x04, 0x00, 0x00, 0x00, 0x00}
	encFW, err := c.EncryptCommand(fwCmd)
	if err != nil {
		t.Fatalf("EncryptCommand(fw): %v", err)
	}
	blk, err := aes.NewCipher(initCmd[16:32])
	if err != nil {
		t.Fatal(err)
	}
	var dec [128]byte
	for off := 0; off < 128; off += aes.BlockSize {
		blk.Decrypt(dec[off:off+aes.BlockSize], encFW[2+off:2+off+aes.BlockSize])
	}
	if !bytes.Equal(dec[:6], fwCmd[2:8]) {
		t.Fatalf("AES-128 decrypt mismatch: got %x want %x", dec[:6], fwCmd[2:8])
	}
}

func TestXORCipherRoundTrip(t *testing.T) {
	var x XORCipher
	x.SetKey(sessionXORKey[:])

	orig := make([]byte, 188)
	orig[0] = 0x47
	orig[1] = 0x21 // priority=1, PID high=1
	orig[2] = 0x00 // PID = 0x0100
	orig[3] = 0x80 // scrambling control = 2
	for i := 4; i < 188; i++ {
		orig[i] = byte(i * 7)
	}

	// 暗号化（元のパケットの [4:132] を XOR）
	pkt := append([]byte(nil), orig...)
	x.Crypt(pkt[4:132], pkt[4:132])

	// DecryptPacket で復号され、priority ビットが落ちること
	x.DecryptPacket(pkt)
	if pkt[1]&0x20 != 0 {
		t.Fatalf("priority bit not cleared: %#02x", pkt[1])
	}
	if !bytes.Equal(pkt[4:], orig[4:]) {
		t.Fatalf("payload mismatch after DecryptPacket")
	}
}
